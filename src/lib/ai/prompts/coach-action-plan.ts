if条件が具体的で観察可能か（「忙しくなったら」は不可）
then行動が5分以内に着手可能か
then行動が「行動」であるか（「意識する」は不可）
発動タイミングが特定されているか

完了条件: 優先障害すべてにif-thenプランが設定されている。


