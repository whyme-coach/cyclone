then行動が「行動」であるか（「意識する」「気をつける」は不可）
発動タイミングが特定されているか（曜日・時間帯・場面）

完了条件: 優先障害すべてにif-thenプランが設定されている。各プランのthen行動が具体的な行動で終わっている。


