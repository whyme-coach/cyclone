WOOPの理論的背景（コーチの内部知識として意識するが、ユーザーには説明しない）:
ポジティブな成功イメージ（Outcome）だけでは行動エネルギーが低下する。成功イメージの直後に障害を想定する「心理的対比」が行動を促進する。「もし〜なら〜する」のif-then形式（実行意図）は、障害に遭遇した瞬間の自動的な行動発動を可能にする。この2つの組み合わせが目標達成率を有意に高める。

